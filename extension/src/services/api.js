// ==========================================
// 1. Chrome Background Communication
// ==========================================

async function sendBackendMessage(message) {

  // Check whether the Chrome extension
  // runtime is available.
  if (
    typeof chrome === "undefined" ||
    !chrome.runtime?.id
  ) {
    throw new Error(
      "Chrome extension runtime is unavailable."
    );
  }

  let response;

  try {

    // Send request to background.js.
    response = await chrome.runtime.sendMessage(
      message
    );

  } catch (error) {

    console.error(
      "WebMind background communication error:",
      error
    );

    throw new Error(
      "Could not communicate with the WebMind " +
      "background service. Reload the extension."
    );
  }

  // Check for missing response.
  if (!response) {
    throw new Error(
      "No response from WebMind background service."
    );
  }

  // Handle backend/API errors.
  if (!response.success) {
    throw new Error(
      response.error ||
      "Backend request failed."
    );
  }

  // Return the response generated by FastAPI.
  return response.data;
}


// ==========================================
// Module 5: Upload Webpage to SQLite
// ==========================================

export async function ingestPage(pageData) {

  if (
    !pageData ||
    typeof pageData !== "object"
  ) {
    throw new Error(
      "Analyze the webpage first."
    );
  }

  if (
    typeof pageData.url !== "string" ||
    !pageData.url
  ) {
    throw new Error(
      "Extracted webpage URL is missing."
    );
  }

  return sendBackendMessage({
    type: "WEBMIND_INGEST_PAGE",
    payload: pageData
  });
}


